// Embed server/chat/system-prompts/*.md as strings (runtime-agnostic: no fs at request time).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const DIR = join(process.cwd(), 'server', 'chat', 'system-prompts');

export function generatePrompts(): string {
  const files = readdirSync(DIR).filter((f) => f.endsWith('.md')).sort();
  const entries = files.map((f) => {
    const body = readFileSync(join(DIR, f), 'utf8').replace(/^<!--.*?-->\n/, '');
    return `  ${JSON.stringify(f.replace(/\.md$/, ''))}: ${JSON.stringify(body)},`;
  });
  return `// © 2026 Dea Saka Kurnia Putra. All rights reserved.\n// GENERATED by scripts/build/gen-prompts.ts from server/chat/system-prompts/*.md — do not edit.\n\nexport const PROMPTS: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(join(process.cwd(), 'server', 'chat', 'prompts.generated.ts'), generatePrompts());
  console.log('prompts.generated.ts written');
}
