// Bundles the Vercel function (server/adapters/vercel.ts) into one ESM file, api/index.mjs. Vercel's Node
// builder transpiles per file and cannot resolve the codebase's extensionless imports at runtime, so the
// function ships pre-bundled. Run after any server change: `npm run build:api` (CI checks it is current).
import { build } from 'esbuild';

await build({
  entryPoints: ['server/adapters/vercel.ts'],
  outfile: 'api/index.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  minify: true,
  legalComments: 'none',
  banner: { js: "// © 2026 Dea Saka Kurnia Putra. All rights reserved.\n// GENERATED by scripts/build/bundle-api.ts — do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
});
console.log('api/index.mjs bundled');
